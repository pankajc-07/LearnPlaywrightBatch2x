for (let i = 0; i < 5; i++) {
    console.log("Value of i is = " + i);
}
console.log("****************************************");

// It does not matter i++/++i in for loop, as code is printed in next line only
for (let j = 0; j < 5; ++j) {
    console.log("Value of j is = " + j);
}
console.log("****************************************");

for (let k = 0; k <= 5; k++) {
    console.log("Value of k = " + k);
}
